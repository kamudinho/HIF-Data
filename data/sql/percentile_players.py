# data/sql/percentile_players.py

import pandas as pd
from data.data_load import _get_snowflake_conn

def fetch_player_percentiles(connection=None) -> pd.DataFrame:
    """
    Henter spillerstatistik og percentiler. Henter automatisk forbindelse,
    hvis den ikke er angivet.
    """
    if connection is None:
        connection = _get_snowflake_conn()

    sql_query = """
    WITH MatchBaseAll AS (
        SELECT 
            MATCH_OPTAUUID, 
            TO_CHAR(MATCH_DATE_FULL, 'YYYY-MM-DD') AS MATCH_DATE,
            CONTESTANTHOME_OPTAUUID, 
            CONTESTANTAWAY_OPTAUUID,
            CONTESTANTHOME_NAME,
            CONTESTANTAWAY_NAME
        FROM KLUB_HVIDOVREIF.AXIS.OPTA_MATCHINFO
        WHERE TOURNAMENTCALENDAR_OPTAUUID = '2mb332vncy4450vu14paj8844'
          AND MATCH_STATUS = 'Played'
          AND MATCH_DATE_FULL <= CURRENT_DATE()
    ),
    PlayerStatsAgg AS (
        SELECT 
            PLAYER_OPTAUUID,
            CONTESTANT_OPTAUUID,
            COUNT(DISTINCT MATCH_ID) AS KAMPE,
            SUM(CASE WHEN STAT_TYPE = 'minsPlayed' THEN CAST(STAT_VALUE AS FLOAT) ELSE 0 END) AS MINUTES_PLAYED,
            
            -- Mål & xG
            SUM(CASE WHEN STAT_TYPE = 'goals' THEN CAST(STAT_VALUE AS FLOAT) ELSE 0 END) AS GOALS,
            SUM(CASE WHEN STAT_TYPE = 'penaltyGoals' THEN CAST(STAT_VALUE AS FLOAT) ELSE 0 END) AS PENALTY_GOALS,
            SUM(CASE WHEN STAT_TYPE = 'expectedGoals' THEN CAST(STAT_VALUE AS FLOAT) ELSE 0 END) AS XG,
            SUM(CASE WHEN STAT_TYPE = 'expectedGoalsNonpenalty' THEN CAST(STAT_VALUE AS FLOAT) ELSE 0 END) AS NP_XG,
            
            -- Assists & xA
            SUM(CASE WHEN STAT_TYPE = 'goalAssist' THEN CAST(STAT_VALUE AS FLOAT) ELSE 0 END) AS ASSISTS,
            SUM(CASE WHEN STAT_TYPE = 'expectedAssists' THEN CAST(STAT_VALUE AS FLOAT) ELSE 0 END) AS XA,
            
            -- Skud & Kreativitet
            SUM(CASE WHEN STAT_TYPE = 'totalScoringAtt' THEN CAST(STAT_VALUE AS FLOAT) ELSE 0 END) AS SHOTS,
            SUM(CASE WHEN STAT_TYPE = 'totalAttAssist' THEN CAST(STAT_VALUE AS FLOAT) ELSE 0 END) AS KEY_PASSES,
            SUM(CASE WHEN STAT_TYPE = 'touchesInOppBox' THEN CAST(STAT_VALUE AS FLOAT) ELSE 0 END) AS TOUCHES_IN_BOX,
            SUM(CASE WHEN STAT_TYPE = 'bigChanceCreated' THEN CAST(STAT_VALUE AS FLOAT) ELSE 0 END) AS BIG_CHANCES_CREATED,
            SUM(CASE WHEN STAT_TYPE = 'touches' THEN CAST(STAT_VALUE AS FLOAT) ELSE 0 END) AS TOTAL_TOUCHES
        FROM KLUB_HVIDOVREIF.AXIS.OPTA_MATCHEXPECTEDGOALS
        WHERE MATCH_ID IN (SELECT MATCH_OPTAUUID FROM MatchBaseAll)
        GROUP BY PLAYER_OPTAUUID, CONTESTANT_OPTAUUID
    ),
    PlayerEventsAgg AS (
        SELECT 
            e.PLAYER_OPTAUUID,
            e.EVENT_CONTESTANT_OPTAUUID AS CONTESTANT_OPTAUUID,
            -- Afleveringer
            SUM(CASE WHEN e.EVENT_TYPEID = 1 THEN 1 ELSE 0 END) AS TOTAL_PASSES,
            SUM(CASE WHEN e.EVENT_TYPEID = 1 AND e.EVENT_OUTCOME = 1 THEN 1 ELSE 0 END) AS ACCURATE_PASSES,
            -- Offensiv / Driblinger / Dueller
            SUM(CASE WHEN e.EVENT_TYPEID = 3 THEN 1 ELSE 0 END) AS DRIBBLES_ATTEMPTED,
            SUM(CASE WHEN e.EVENT_TYPEID = 3 AND e.EVENT_OUTCOME = 1 THEN 1 ELSE 0 END) AS DRIBBLES_SUCC,
            SUM(CASE WHEN e.EVENT_TYPEID = 44 THEN 1 ELSE 0 END) AS AERIAL_DUELS_TOTAL,
            SUM(CASE WHEN e.EVENT_TYPEID = 44 AND e.EVENT_OUTCOME = 1 THEN 1 ELSE 0 END) AS AERIAL_DUELS_WON,
            -- Forsvar & Defensive aktioner
            SUM(CASE WHEN e.EVENT_TYPEID = 7 THEN 1 ELSE 0 END) AS TACKLES_ATTEMPTED,
            SUM(CASE WHEN e.EVENT_TYPEID = 7 AND e.EVENT_OUTCOME = 1 THEN 1 ELSE 0 END) AS TACKLES_WON,
            SUM(CASE WHEN e.EVENT_TYPEID = 8 THEN 1 ELSE 0 END) AS INTERCEPTIONS,
            SUM(CASE WHEN e.EVENT_TYPEID = 12 THEN 1 ELSE 0 END) AS CLEARANCES,
            SUM(CASE WHEN e.EVENT_TYPEID = 43 THEN 1 ELSE 0 END) AS BALL_RECOVERIES,
            -- Disiplin & Fejl
            SUM(CASE WHEN e.EVENT_TYPEID = 4 THEN 1 ELSE 0 END) AS FOULS_CONCEDED,
            SUM(CASE WHEN e.EVENT_TYPEID = 49 THEN 1 ELSE 0 END) AS FOULS_WON
        FROM KLUB_HVIDOVREIF.AXIS.OPTA_EVENTS e
        WHERE e.MATCH_OPTAUUID IN (SELECT MATCH_OPTAUUID FROM MatchBaseAll)
        GROUP BY e.PLAYER_OPTAUUID, e.EVENT_CONTESTANT_OPTAUUID
    ),
    PlayerNames AS (
        SELECT 
            PLAYER_OPTAUUID,
            MAX(COALESCE(MATCH_NAME, FIRST_NAME || ' ' || LAST_NAME)) AS PLAYER_NAME
        FROM KLUB_HVIDOVREIF.AXIS.OPTA_MATCH_LINEUPS
        WHERE FIRST_NAME IS NOT NULL
        GROUP BY PLAYER_OPTAUUID
    ),
    TeamMapping AS (
        SELECT CONTESTANT_OPTAUUID, MAX(CONTESTANT_NAME) AS TEAM_NAME
        FROM (
            SELECT CONTESTANTHOME_OPTAUUID AS CONTESTANT_OPTAUUID, CONTESTANTHOME_NAME AS CONTESTANT_NAME FROM MatchBaseAll
            UNION
            SELECT CONTESTANTAWAY_OPTAUUID AS CONTESTANT_OPTAUUID, CONTESTANTAWAY_NAME AS CONTESTANT_NAME FROM MatchBaseAll
        )
        GROUP BY CONTESTANT_OPTAUUID
    ),
    BaseCalculations AS (
        SELECT 
            COALESCE(tm.TEAM_NAME, p.CONTESTANT_OPTAUUID) AS HOLD_NAVN,
            COALESCE(pn.PLAYER_NAME, p.PLAYER_OPTAUUID) AS SPILLER_NAVN,
            p.MINUTES_PLAYED AS MINUTTER,
            p.KAMPE,
            
            -- Offensive P90 metrikker
            ROUND((p.GOALS - COALESCE(p.PENALTY_GOALS, 0)) / NULLIF(p.MINUTES_PLAYED, 0) * 90, 2) AS NP_GOALS_P90,
            ROUND(COALESCE(p.NP_XG, p.XG) / NULLIF(p.MINUTES_PLAYED, 0) * 90, 2) AS NP_XG_P90,
            ROUND(p.XG / NULLIF(p.MINUTES_PLAYED, 0) * 90, 2) AS XG_P90,
            ROUND(p.XA / NULLIF(p.MINUTES_PLAYED, 0) * 90, 2) AS XA_P90,
            ROUND(p.ASSISTS / NULLIF(p.MINUTES_PLAYED, 0) * 90, 2) AS ASSISTS_P90,
            ROUND(p.SHOTS / NULLIF(p.MINUTES_PLAYED, 0) * 90, 2) AS SHOTS_P90,
            ROUND(p.KEY_PASSES / NULLIF(p.MINUTES_PLAYED, 0) * 90, 2) AS KEY_PASSES_P90,
            ROUND(p.TOUCHES_IN_BOX / NULLIF(p.MINUTES_PLAYED, 0) * 90, 2) AS TOUCHES_IN_BOX_P90,
            ROUND(p.BIG_CHANCES_CREATED / NULLIF(p.MINUTES_PLAYED, 0) * 90, 2) AS BIG_CHANCES_CREATED_P90,
            
            -- Afleveringer & boldbesiddelse
            ROUND(COALESCE(e.TOTAL_PASSES, 0) / NULLIF(p.MINUTES_PLAYED, 0) * 90, 2) AS PASSES_ATTEMPTED_P90,
            ROUND(COALESCE(e.ACCURATE_PASSES, 0) * 100.0 / NULLIF(e.TOTAL_PASSES, 0), 1) AS PASS_COMPLETION_PCT,
            
            -- Defensive hændelser P90
            ROUND(COALESCE(e.TACKLES_WON, 0) / NULLIF(p.MINUTES_PLAYED, 0) * 90, 2) AS TACKLES_WON_P90,
            ROUND(COALESCE(e.INTERCEPTIONS, 0) / NULLIF(p.MINUTES_PLAYED, 0) * 90, 2) AS INTERCEPTIONS_P90,
            ROUND(COALESCE(e.CLEARANCES, 0) / NULLIF(p.MINUTES_PLAYED, 0) * 90, 2) AS CLEARANCES_P90,
            ROUND(COALESCE(e.BALL_RECOVERIES, 0) / NULLIF(p.MINUTES_PLAYED, 0) * 90, 2) AS BALL_RECOVERIES_P90,
            
            -- Dueller & Driblinger P90
            ROUND(COALESCE(e.DRIBBLES_SUCC, 0) / NULLIF(p.MINUTES_PLAYED, 0) * 90, 2) AS DRIBBLES_SUCC_P90,
            ROUND(COALESCE(e.AERIAL_DUELS_WON, 0) / NULLIF(p.MINUTES_PLAYED, 0) * 90, 2) AS AERIAL_DUELS_WON_P90,
            ROUND(COALESCE(e.AERIAL_DUELS_TOTAL, 0) * 100.0 / NULLIF(e.AERIAL_DUELS_TOTAL, 0), 1) AS AERIAL_WIN_PCT

        FROM PlayerStatsAgg p
        LEFT JOIN PlayerEventsAgg e ON p.PLAYER_OPTAUUID = e.PLAYER_OPTAUUID AND p.CONTESTANT_OPTAUUID = e.CONTESTANT_OPTAUUID
        LEFT JOIN PlayerNames pn ON p.PLAYER_OPTAUUID = pn.PLAYER_OPTAUUID
        LEFT JOIN TeamMapping tm ON p.CONTESTANT_OPTAUUID = tm.CONTESTANT_OPTAUUID
        WHERE p.MINUTES_PLAYED >= 200
    )
    SELECT 
        HOLD_NAVN,
        SPILLER_NAVN,
        MINUTTER,
        KAMPE,
        
        -- Værdier + tilhørende Percentiler (0-100)
        NP_GOALS_P90, ROUND(PERCENT_RANK() OVER (ORDER BY NP_GOALS_P90 ASC) * 100, 1) AS NP_GOALS_PCTILE,
        NP_XG_P90, ROUND(PERCENT_RANK() OVER (ORDER BY NP_XG_P90 ASC) * 100, 1) AS NP_XG_PCTILE,
        SHOTS_P90, ROUND(PERCENT_RANK() OVER (ORDER BY SHOTS_P90 ASC) * 100, 1) AS SHOTS_PCTILE,
        ASSISTS_P90, ROUND(PERCENT_RANK() OVER (ORDER BY ASSISTS_P90 ASC) * 100, 1) AS ASSISTS_PCTILE,
        XA_P90, ROUND(PERCENT_RANK() OVER (ORDER BY XA_P90 ASC) * 100, 1) AS XA_PCTILE,
        KEY_PASSES_P90, ROUND(PERCENT_RANK() OVER (ORDER BY KEY_PASSES_P90 ASC) * 100, 1) AS KEY_PASSES_PCTILE,
        PASSES_ATTEMPTED_P90, ROUND(PERCENT_RANK() OVER (ORDER BY PASSES_ATTEMPTED_P90 ASC) * 100, 1) AS PASSES_ATTEMPTED_PCTILE,
        PASS_COMPLETION_PCT, ROUND(PERCENT_RANK() OVER (ORDER BY PASS_COMPLETION_PCT ASC) * 100, 1) AS PASS_COMPLETION_PCTILE,
        TOUCHES_IN_BOX_P90, ROUND(PERCENT_RANK() OVER (ORDER BY TOUCHES_IN_BOX_P90 ASC) * 100, 1) AS TOUCHES_IN_BOX_PCTILE,
        TACKLES_WON_P90, ROUND(PERCENT_RANK() OVER (ORDER BY TACKLES_WON_P90 ASC) * 100, 1) AS TACKLES_WON_PCTILE,
        INTERCEPTIONS_P90, ROUND(PERCENT_RANK() OVER (ORDER BY INTERCEPTIONS_P90 ASC) * 100, 1) AS INTERCEPTIONS_PCTILE,
        CLEARANCES_P90, ROUND(PERCENT_RANK() OVER (ORDER BY CLEARANCES_P90 ASC) * 100, 1) AS CLEARANCES_PCTILE,
        BALL_RECOVERIES_P90, ROUND(PERCENT_RANK() OVER (ORDER BY BALL_RECOVERIES_P90 ASC) * 100, 1) AS BALL_RECOVERIES_PCTILE,
        DRIBBLES_SUCC_P90, ROUND(PERCENT_RANK() OVER (ORDER BY DRIBBLES_SUCC_P90 ASC) * 100, 1) AS DRIBBLES_SUCC_PCTILE,
        AERIAL_DUELS_WON_P90, ROUND(PERCENT_RANK() OVER (ORDER BY AERIAL_DUELS_WON_P90 ASC) * 100, 1) AS AERIAL_DUELS_WON_PCTILE
    FROM BaseCalculations
    ORDER BY HOLD_NAVN, SPILLER_NAVN;
    """  # <--- Sørg for at denne lukker sql_query strengen korrekt!

    return connection.query(sql_query, ttl=0)
